def region_base(name: str) -> str:
    """'성남시' → '성남', '경상북도' → '경북', '서울특별시' → '서울', '인천 동구' → '동구'(마지막 어절). 접미어를 떼면 1음절이 되면 그대로."""
    part = (name or "").split()[-1] if (name or "").split() else ""
    for sfx in _REGION_SUFFIX:
        if part.endswith(sfx) and len(part) - len(sfx) >= 2:
            part = part[: -len(sfx)]
            break
    return WIDE_CANON.get(part, part)


def region_parents(name: str) -> set[str]:
    """지역 문자열에 든 광역 약칭 ('인천 동구' → {인천}, '성남시' → {경기}, '경북' → {경북})."""
    out: set[str] = set()
    for part in (name or "").split():
        b = region_base(part)
        if b in WIDE_CANON.values():
            out.add(b)
        elif b in PARENT:
            out.add(PARENT[b])
    return out


def is_wide_region(name: str) -> bool:
    """시드 지역이 광역(도·특별시·광역시) 단위인가. '인천 동구'·'제주시'·'성남시' 는 기초."""
    parts = (name or "").split()
    if len(parts) != 1:
        return False
    p = parts[0]
    b = region_base(p)
    if b not in WIDE_CANON.values():
        return False
    if b in METROS:
        return True
    return not p.endswith(("시", "군", "구"))  # '제주시' 는 기초 도시, '경북'·'경상북도' 는 광역
