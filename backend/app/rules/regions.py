def is_admin_region(name: str, lexicon: tuple[str, ...] | list[str] = ()) -> bool:
    n = (name or "").strip()
    if not n:
        return False
    if n in ADMIN_NAMES or n in lexicon:
        return True
    return any(n == a or n.rstrip("청") == a for a in lexicon)

